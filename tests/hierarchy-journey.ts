import { expect, type Page } from '@playwright/test';
export async function hierarchyJourney(page: Page) {
  const account = (await (await page.request.get('/api/v1/auth/session')).json()).account;
  const root = '/api/v1/households/' + account.households[0].id;
  const headers = { origin: new URL(page.url()).origin };
  const create = async (path: string, data: object) => { const response = await page.request.post(root + path, { headers, data }); expect(response.ok()).toBe(true); return response.json(); };
  const car = await create('/entities', { kind: 'resource', name: 'Family car' });
  const ladder = await create('/entities', { kind: 'resource', name: 'Tall ladder' });
  const trailer = await create('/entities', { kind: 'resource', name: 'Utility trailer', icon: 'trailer' });
  const permit = await create('/tasks', { title: 'Obtain permit', column: 'done' });
  const parent = await create('/tasks', { title: 'Renovate shed', column: 'within_year', high: true, resources: [car.id, ladder.id], blockers: [permit.id] });
  await page.getByRole('navigation').getByRole('button', { name: 'Board', exact: true }).filter({ visible: true }).click();
  await page.getByRole('button', { name: 'Renovate shed', exact: true }).click();
  await page.getByLabel('New subtask', { exact: true }).fill('Prepare shed');
  await page.getByRole('button', { name: 'Add subtask', exact: true }).click();
  await page.getByRole('button', { name: 'Prepare shed Someday', exact: true }).click();
  await expect(page.getByRole('button', { name: 'High priority', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('combobox', { name: 'Column', exact: true }).selectOption('todo');
  await expect(page.getByRole('dialog').getByRole('status').first()).toContainText('Saved');
  await expect(page.getByRole('heading', { name: 'Planning details', exact: true })).toBeVisible();
  await page.getByRole('combobox', { name: 'Family car · Resources', exact: true }).selectOption('exclude');
  await expect(page.getByRole('dialog').getByRole('status').first()).toContainText('Saved');
  const changed = await page.request.patch(root + '/tasks/' + parent.id, { headers, data: { baseVersion: parent.version, changes: { resources: [car.id, ladder.id, trailer.id] } } });
  expect(changed.ok()).toBe(true);
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('navigation').getByRole('button', { name: 'Now', exact: true }).filter({ visible: true }).click();
  await page.getByRole('button', { name: 'Prepare shed', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Planning details', exact: true })).toBeVisible();
  await expect(page.getByText('Currently applies:', { exact: false }).filter({ hasText: 'Tall ladder' }).filter({ hasText: 'Utility trailer' })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByText('Blocked by', { exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/hierarchy-mobile-dark.png' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.getByRole('navigation').getByRole('button', { name: 'Board', exact: true }).filter({ visible: true }).click();
  await page.getByRole('button', { name: 'Renovate shed', exact: true }).click();
  await page.getByRole('combobox', { name: 'Column', exact: true }).selectOption('done');
  await expect(page.getByRole('button', { name: 'Complete this task anyway', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Complete this task anyway', exact: true }).click();
  await expect(page.getByRole('dialog').getByRole('status').first()).toContainText('Saved');
  await expect(page.getByRole('button', { name: 'Prepare shed To Do', exact: true })).toBeVisible();
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
  const reopened = await page.request.patch(root + '/tasks/' + permit.id, { headers, data: { baseVersion: permit.version, changes: { column: 'todo' } } });
  expect(reopened.ok()).toBe(true);
  await page.getByRole('navigation').getByRole('button', { name: 'Now', exact: true }).filter({ visible: true }).click();
  await expect(page.getByRole('button', { name: 'Prepare shed', exact: true })).toHaveCount(0);
}
