import { expect, type Page } from '@playwright/test';
export async function vpJourney(page: Page) {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('navigation').getByRole('button', { name: 'More', exact: true }).filter({ visible: true }).click();
  await page.getByRole('button', { name: 'Views and filters', exact: true }).click();
  await page.getByRole('heading', { name: 'Saved filters', exact: true }).locator('..').getByRole('button', { name: 'Create', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('Available work');
  await page.getByRole('button', { name: 'Add condition', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Live preview' })).toBeVisible();
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('heading', { name: 'Saved views', exact: true }).locator('..').getByRole('button', { name: 'Create', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('Weekend planning');
  await page.getByLabel('Available work', { exact: true }).check();
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.locator('.planning-documents article').filter({ hasText: 'Weekend planning' }).getByRole('button', { name: 'Open', exact: true }).click();
  const chip = page.getByRole('button', { name: 'Available work', exact: true });
  await chip.click(); await expect(chip).toHaveAttribute('aria-pressed', 'true');
  await page.keyboard.press('n');
  await page.getByLabel('What needs doing?', { exact: true }).fill('VP household inspection');
  await page.getByRole('button', { name: 'Add task', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const source = page.getByRole('button', { name: 'VP household inspection', exact: true });
  await source.dragTo(page.locator('.board-column').filter({ has: page.getByRole('heading', { name: 'To Do', exact: true }) }));
  await expect(page.locator('.board-column').filter({ has: page.getByRole('heading', { name: 'To Do', exact: true }) }).getByRole('button', { name: 'VP household inspection', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'VP household inspection', exact: true }).click();
  const contentBounds = (await page.locator('.task-detail-content').boundingBox())!;
  const planningBounds = (await page.locator('.task-detail-properties').boundingBox())!;
  expect(planningBounds.x).toBeGreaterThanOrEqual(contentBounds.x + contentBounds.width - 1);
  await page.screenshot({ path: 'test-results/task-desktop-redesign.png' });
  await page.getByRole('textbox', { name: 'Description', exact: true }).fill('Inspection notes');
  await expect(page.locator('.save-status')).toContainText('Saved');
  await page.getByRole('textbox', { name: 'Comment', exact: true }).fill('Remember the brass fitting');
  await page.getByRole('button', { name: 'Post comment', exact: true }).click();
  await expect(page.locator('.comments-list')).toContainText('Remember the brass fitting');
  await page.locator('.content-panel input[type=file]').first().setInputFiles({ name: 'inspection.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64') });
  await expect(page.locator('.attachment-grid img')).toBeVisible();
  await page.getByRole('button', { name: 'Save as template / series', exact: true }).click();
  await page.getByRole('dialog').last().getByLabel('Name', { exact: true }).fill('Yearly inspection');
  await page.getByLabel('Create recurring occurrences').check();
  await page.getByLabel('First scheduled date').fill('2035-10-01');
  await page.getByRole('dialog').last().getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.getByText('Template saved. Manage it under More → Templates and series.', { exact: true })).toBeVisible();
  await expect(page.getByRole('dialog')).toHaveCount(1);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/vp-mobile-content.png', fullPage: true });
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await page.getByRole('searchbox', { name: 'Search', exact: true }).fill('brass fitting');
  await expect(page.locator('.search-results')).toContainText('VP household inspection');
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('navigation').getByRole('button', { name: 'More', exact: true }).filter({ visible: true }).click();
  await page.getByRole('button', { name: 'Templates and series', exact: true }).click();
  await expect(page.locator('.planning-documents')).toContainText('Yearly inspection');
  await page.setViewportSize({ width: 1440, height: 1000 });
}
