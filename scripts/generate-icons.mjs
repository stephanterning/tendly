const names = [...source.matchAll(/"([a-z0-9-]+)":/g)].map(match => match[1]);
await writeFile(new URL('../packages/shared/src/icons.ts', import.meta.url), '// Generated by scripts/generate-icons.mjs when updating lucide-react.\nexport const iconNames = ' + JSON.stringify([...names, 'trailer', 'trailer-covered'], null, 2) + ' as const;\n');
